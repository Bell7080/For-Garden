/**
 * 편성 칸 밑판의 공용 생김새 값.
 *
 * Phaser 없는 순수 모듈에 두는 이유는 회귀 테스트가 그리기 구현이 아니라 이 값을 읽어야 하기
 * 때문이다 — 그리는 것은 `formationSlotChrome.ts`의 `addFormationSlotPlate` 한 곳이다.
 *
 * 네 화면(스토리·원정·발굴·교류 파견)이 같은 세 자리를 고르므로 칸도 같은 판이어야 한다.
 * 기준은 이미 잘 읽히던 **발굴의 칸**이다 — 반투명 유리면 한 장을 늘 깔고, 누군가 서 있으면
 * 발밑에 얇은 투영 그림자만 두며, 비었으면 자리 번호가 그 자리를 지킨다.
 *
 * 판을 **서 있을 때만 감추지 않는다**. 원정이 그랬는데, 세 자리 중 둘만 차면 남은 한 칸만
 * 판이 보여 빈 자리가 "못 쓰는 자리"처럼 읽혔다. 세 칸이 늘 같은 판 위에 서야 무엇을 더
 * 고를 수 있는지가 한눈에 보인다.
 */
export const FORMATION_SLOT_PLATE = {
  /** 판 윗변 강조선의 진하기. */
  edgeAlpha: 0.55,
  /** 발밑 투영 그림자 — 칸 폭 대비 너비, 높이, 진하기. */
  groundWidthRatio: 0.82,
  groundHeight: 25,
  groundAlpha: 0.16,
  /** 빈 칸에 서는 자리 번호의 크기. */
  emptyFontSize: 22,
} as const;
