/**
 * SD 발밑 그림자의 결 — **Phaser 없는 순수 표**.
 *
 * SD가 서는 자리는 어디서나 이 한 벌이다(정보창·적 창·소환수 창·신규 개체 소개의 받침, 전장, 편성
 * 칸, 편성 적 줄, 노드 적 미리보기, 결과판, 프로필 카드). 화면마다 제 나름의 타원을 깔던 때는 같은
 * SD가 어디서는 노란 선이 그어진 짙은 원판 위에, 어디서는 강조색 빛 위에, 어디서는 맨 검정 위에 섰다.
 *
 * **판이 아니라 그림자다.** 선을 긋지 않고, 같은 타원을 조금씩 줄여 가며 옅은 검정을 겹친다 — 가장자리는
 * 거의 비치고 발 바로 아래만 짙어져 흐리기(blur) 없이도 번지는 그림자로 읽힌다. 캔버스 흐리기는 SD마다
 * 텍스처를 구워야 해 전장에서 여섯이 움직이면 그대로 프레임 비용이 된다.
 */
export const SD_FOOT_SHADOW = {
  color: 0x000000,
  /** 폭 대비 높이. 위에서 비스듬히 내려다보는 바닥이라 납작하다. */
  heightRatio: 0.2,
  /** 바깥에서 안쪽으로 겹치는 타원. 다 겹친 가운데도 절반을 넘지 않는다. */
  layers: [
    { scale: 1, alpha: 0.12 },
    { scale: 0.74, alpha: 0.15 },
    { scale: 0.48, alpha: 0.18 },
  ],
} as const;

/** 겹이 모두 포개진 가운데의 진하기. 겹친 반투명 면은 곱으로 비친다. */
export function sdFootShadowCoreAlpha(): number {
  return 1 - SD_FOOT_SHADOW.layers.reduce((through, layer) => through * (1 - layer.alpha), 1);
}
