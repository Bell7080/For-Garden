/**
 * 머리 위 상태 칩 안에 서는 **상태마다 다른 그림**.
 *
 * 예전 칩은 모든 상태가 같은 마름모 한 장이고 색만 달랐다. 칩이 22px이라 색 몇 가지가 서로
 * 비슷해지면(둔화·여울·수압이 모두 물빛, 졸음·잠·위압이 모두 보랏빛) 무엇이 걸렸는지 눌러
 * 보기 전에는 알 수 없었다. 지금은 **색이 계열을, 그림이 상태를** 말한다.
 *
 * Phaser를 모르는 순수 표다 — 좌표는 칩 중심을 원점으로 한 **단위 좌표**(−1~1, 아래가 +y)이고,
 * 칩이 크기를 곱해 그린다. 테스트가 모든 상태에 그림이 있는지, 칩 밖으로 나가지 않는지,
 * 두 상태가 같은 그림을 쓰지 않는지를 이 표로 잰다.
 *
 * 그림은 **면 + 굵은 선** 두 종류뿐이다. 이만큼 작은 칩에서 가는 선은 사라지므로 선은 늘
 * 굵게 긋고, 칩이 같은 모양을 검게 한 번 더 두껍게 깔아(잉크 외곽) 어떤 배경 위에서도 떨어진다.
 */
export type GlyphPoint = readonly [number, number];
export type StatusGlyphPart =
  | { kind: "fill"; points: readonly GlyphPoint[] }
  | { kind: "line"; points: readonly GlyphPoint[]; closed?: boolean };
export type StatusGlyph = readonly StatusGlyphPart[];

const fill = (...points: GlyphPoint[]): StatusGlyphPart => ({ kind: "fill", points });
const line = (...points: GlyphPoint[]): StatusGlyphPart => ({ kind: "line", points });
const ring = (...points: GlyphPoint[]): StatusGlyphPart => ({ kind: "line", points, closed: true });

/** 네 갈래 별. `r`은 갈래 끝, `w`는 허리의 굵기. */
function sparkle(cx: number, cy: number, r: number, w = 0.32): StatusGlyphPart {
  const k = r * w;
  return fill([cx, cy - r], [cx + k, cy - k], [cx + r, cy], [cx + k, cy + k], [cx, cy + r], [cx - k, cy + k], [cx - r, cy], [cx - k, cy - k]);
}

/** 위가 뾰족하고 아래가 둥근(팔각으로 깎은) 물방울. */
function drop(cx: number, cy: number, r: number): StatusGlyphPart {
  return fill([cx, cy - r * 1.35], [cx + r * 0.62, cy - r * 0.2], [cx + r * 0.78, cy + r * 0.32], [cx + r * 0.5, cy + r * 0.78],
    [cx, cy + r * 0.95], [cx - r * 0.5, cy + r * 0.78], [cx - r * 0.78, cy + r * 0.32], [cx - r * 0.62, cy - r * 0.2]);
}

/** 각진 방패 윤곽. */
const SHIELD: GlyphPoint[] = [[-0.62, -0.72], [0.62, -0.72], [0.62, 0.05], [0, 0.78], [-0.62, 0.05]];

/** 팔각으로 깎은 작은 방울(거품). 동그라미를 쓰지 않는 결을 따른다. */
function bead(cx: number, cy: number, r: number): StatusGlyphPart {
  const k = r * 0.42;
  return fill([cx - k, cy - r], [cx + k, cy - r], [cx + r, cy - k], [cx + r, cy + k], [cx + k, cy + r], [cx - k, cy + r], [cx - r, cy + k], [cx - r, cy - k]);
}

/** 여섯 갈래 눈송이. */
function snowflake(r: number): StatusGlyphPart[] {
  return [0, 1, 2].map((index) => {
    const angle = index * Math.PI / 3 - Math.PI / 2;
    const x = Math.cos(angle) * r;
    const y = Math.sin(angle) * r;
    return line([-x, -y], [x, y]);
  });
}

/** 지그재그 Z 한 글자. */
function zee(cx: number, cy: number, s: number): StatusGlyphPart {
  return line([cx - s, cy - s], [cx + s, cy - s], [cx - s, cy + s], [cx + s, cy + s]);
}

