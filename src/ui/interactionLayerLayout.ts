import { BASE_HEIGHT, BASE_WIDTH } from "../config/gameConfig";

/**
 * 교류지 목록의 자리표.
 *
 * **한 줄이 아니라 한 장이다.** 예전에는 176px 두께에 폭만 960px인 **가로로 긴 띠**였다 —
 * 그 비율에 도시 원화를 넣으면 세로가 통째로 잘려 하늘 한 줄이나 바닥 한 줄만 남았고, 무엇을
 * 그린 그림인지 읽히지 않았다. 그러면서 목록은 목록대로 길어 한 화면에 넷밖에 서지 못했다.
 * 지금은 원화가 제 모습으로 읽히는 비율(약 4:1 → 4:1보다 훨씬 두꺼운 판)로 세우고, 글은 판
 * 위에 얹지 않고 **아래쪽에서 올라오는 어둠 위에** 놓는다.
 *
 * **좌우로 번갈아 뻗지 않는다.** 지그재그는 훑는 눈을 매 줄 좌우로 끌고 다녀 목록이 정신없이
 * 읽혔다. 층은 모두 같은 x에 선다. **화면 밖으로 넘치지도 않는다** — 양 끝이 화면 밖이면 층
 * 하나가 어디서 시작해 어디서 끝나는지가 화면 안에 없다.
 */
export const INTERACTION_LAYER = {
  /** 목록이 흐르는 창. 우하단 뒤로가기 자리를 침범하지 않는 높이에서 끊는다. */
  viewport: { top: 292, bottom: BASE_HEIGHT - 250 },
  /** 화면 양옆에 같은 여백을 남기고 가운데에 서는 카드 폭. */
  width: BASE_WIDTH - 92,
  /**
   * 카드 한 장의 두께.
   *
   * 도시 원화가 **무엇을 그린 그림인지 읽힐 만큼**은 두꺼워야 한다. 176px이던 때는 1882×3344
   * 짜리 세로 원화가 스무 남짓의 띠로 잘려 색만 남았다.
   */
  height: 268,
  /** 카드 사이 간격(중심 기준). 두께보다 넉넉히 벌려 카드끼리 붙어 보이지 않게 한다. */
  step: 296,
  /** 첫 카드의 중심 y. 창 윗변에서 카드 절반만큼 내려온 자리다. */
  firstY: 292 + 268 / 2 + 10,
  /**
   * 카드가 기우는 정도.
   *
   * 원화는 네모라 기운 판의 두 삼각형을 채울 수 없다 — 그래서 **원화를 이 값만큼 안으로
   * 넣어** 기운 액자 안에 그림이 든 모양으로 세운다. 액자와 그림의 실루엣이 어긋나면 사방에
   * 두른 테두리가 그림 위를 지나간다.
   */
  slant: 26,
  /** 글이 카드 안에서 갖는 사방 여백. */
  padding: 30,
  /** 글이 판 왼쪽 변에서 얼마나 더 안으로 들어와 시작하는지. */
  textInset: 8,
  /**
   * 아래에서 올라오는 어둠의 높이(카드 두께 대비).
   *
   * 글이 서는 자리만 덮는다 — 카드 전체를 누르면 원화가 잿빛이 되어 **무엇을 그린 그림인지
   * 읽히지 않는다**(이 화면을 다시 짠 이유가 그것이다). 위쪽 절반은 그대로 밝게 둔다.
   */
  scrim: 0.44,
  /** 이름줄과 그 아래 한 줄의 자리(카드 밑변 기준으로 올라오는 높이). */
  nameUp: 86,
  noteUp: 40,
  /** 오른쪽에 서는 소요 시간·상태 칩. */
  chip: { width: 196, height: 62, inset: 26, up: 66 },
  /** 잠긴 카드 가운데에 서는 자물쇠 크기. */
  lock: 76,
  /**
   * 글이 서는 아래쪽 띠의 결.
   *
   * **어둠 한 겹만으로는 글과 원화가 갈리지 않았다** — 밝은 하늘이나 흰 벽이 그 자리에 오면
   * 그라데이션이 통째로 밝아져 이름이 그림에 묻혔다. 얇은 가로줄을 촘촘히 깔아 그 자리를
   * **투영면**으로 만들면, 아래에 어떤 그림이 와도 같은 결이 한 겹 덮여 글이 늘 같은 바탕
   * 위에 선다. 무늬는 이 한 가지뿐이고 도시마다 다르게 하지 않는다.
   */
  readout: { gap: 7, width: 1, alpha: 0.16 },
} as const;

/**
 * 카드 하나의 중심 좌표.
 *
 * 모든 카드가 화면 가운데에 선다 — 카드마다 자리가 달라지면 목록이 아니라 흩어진 카드로 읽힌다.
 */
export function interactionLayerSpot(index: number): { x: number; y: number } {
  return { x: BASE_WIDTH / 2, y: INTERACTION_LAYER.firstY + index * INTERACTION_LAYER.step };
}

/** 목록 전체가 차지하는 높이. 창보다 길면 그 안에서 흐른다. */
export function interactionLayersHeight(count: number): number {
  if (count <= 0) return 0;
  return (count - 1) * INTERACTION_LAYER.step + INTERACTION_LAYER.height;
}
